#!/usr/bin/env node
// Builds the gallery data (site/data.js) from every styles/NN-name/meta.json + style.md and prompts/govde.md.
// With --kapak it also makes site/kapak.jpg, a 5×5 grid of the poster frames (needs ffmpeg).
//
//   node tools/build-site.cjs           → site/data.js
//   node tools/build-site.cjs --kapak   → site/data.js + site/kapak.jpg
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

const CATEGORIES = [
  { id: 'el-yapimi', name: 'El Yapımı', en: 'Handmade & Craft' },
  { id: 'miras', name: 'Geleneksel Sanatlar', en: 'Traditional Arts' },
  { id: 'baski-cizim', name: 'Baskı & Çizim', en: 'Print & Drawing' },
  { id: 'isik-dijital', name: 'Işık & Dijital', en: 'Light & Digital' },
];

const dirs = fs.readdirSync(path.join(ROOT, 'styles'), { withFileTypes: true })
  .filter(d => d.isDirectory() && /^\d\d-/.test(d.name))
  .map(d => d.name)
  .sort();

const styles = dirs.map(dir => {
  const meta = JSON.parse(read(`styles/${dir}/meta.json`));
  const guide = read(`styles/${dir}/style.md`).trim();
  for (const k of ['id', 'slug', 'name', 'nameEn', 'category', 'tagline', 'bestFor', 'examples', 'palette', 'fonts', 'signature']) {
    if (!(k in meta)) throw new Error(`${dir}/meta.json: missing "${k}"`);
  }
  if (!CATEGORIES.some(c => c.id === meta.category)) throw new Error(`${dir}: unknown category ${meta.category}`);
  for (const f of [`previews/${dir}.mp4`, `previews/${dir}.jpg`]) if (!fs.existsSync(path.join(ROOT, f))) console.warn(`! missing ${f}`);
  return { ...meta, dir, video: `previews/${dir}.mp4`, poster: `previews/${dir}.jpg`, live: `styles/preview.html?s=${dir}&play`, guide };
});

const data = { generated: new Date().toISOString().slice(0, 10), categories: CATEGORIES, styles, body: read('prompts/govde.md') };
fs.mkdirSync(path.join(ROOT, 'site'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'site/data.js'), `/* generated by tools/build-site.cjs — do not edit by hand */\nwindow.KALEYDO = ${JSON.stringify(data, null, 1)};\n`);
console.log(`site/data.js: ${styles.length} styles`);

if (process.argv.includes('--kapak')) {
  const inputs = styles.flatMap(s => ['-i', path.join(ROOT, s.poster)]);
  const n = styles.length, cols = 5, rows = Math.ceil(n / cols);
  const scaled = styles.map((_, i) => `[${i}]scale=216:384,setsar=1[v${i}]`).join(';');
  const layout = styles.map((_, i) => `${(i % cols) * 216}_${Math.floor(i / cols) * 384}`).join('|');
  const filter = `${scaled};${styles.map((_, i) => `[v${i}]`).join('')}xstack=inputs=${n}:layout=${layout}:fill=black`;
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', ...inputs, '-filter_complex', filter, '-frames:v', '1', '-q:v', '3', path.join(ROOT, 'site/kapak.jpg')]);
  console.log(`site/kapak.jpg: ${cols}×${rows} grid`);
}
